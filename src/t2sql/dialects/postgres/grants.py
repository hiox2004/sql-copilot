"""Generate the read-only role's privileges so personal-data columns are unreadable at the source.

Table-level `GRANT SELECT` exposes every column, and a column-level REVOKE cannot subtract from it.
So we revoke everything and grant SELECT only on the columns the dictionary has not flagged `pii`.
The SQL Guard already refuses those columns; this is the second, independent lock in the database.
The role name is a psql variable (`:"ro_user"`), so the generated file is reusable.
"""

from collections.abc import Collection

from t2sql.core.schema_models import SchemaInfo

HEADER = """-- GENERATED by scripts/gen_column_grants.py (schema + the dictionary's pii flags).
-- Do not edit by hand. Apply with:  psql -v ro_user=<role> -f copilot_ro.sql
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM :"ro_user";
"""


def render_readonly_grants(schema: SchemaInfo, blocked: Collection[tuple[str, str]]) -> str:
    blocked_set = {(t.lower(), c.lower()) for t, c in blocked}
    lines = [HEADER.rstrip("\n")]
    for table in schema.tables:
        readable = [c.name for c in table.columns if (table.name, c.name) not in blocked_set]
        if len(readable) == len(table.columns):
            lines.append(f'GRANT SELECT ON "{table.name}" TO :"ro_user";')
        elif readable:
            cols = ", ".join(f'"{c}"' for c in readable)
            lines.append(f'GRANT SELECT ({cols}) ON "{table.name}" TO :"ro_user";')
        # a table whose every column is personal data gets no grant at all
    return "\n".join(lines) + "\n"
